export function format(value, unit = "") {
  if (!Number.isFinite(value)) return "—";
  let base = unit,
    scaled = value;
  if (unit === "kW") {
    base = "W";
    scaled *= 1000;
  }
  if (unit === "TFLOPS") {
    base = "FLOPS";
    scaled *= 1e12;
  }
  const absolute = Math.abs(scaled),
    prefixes = ["", "k", "M", "G", "T", "P", "E", "Z"];
  let i = 0,
    n = scaled;
  while (Math.abs(n) >= 1000 && i < prefixes.length - 1) {
    n /= 1000;
    i++;
  }
  const precision = Math.abs(n) >= 100 ? 0 : Math.abs(n) >= 10 ? 1 : 2;
  const text = n.toLocaleString("fr-FR", {
    maximumFractionDigits: absolute < 1 && absolute > 0 ? 3 : precision,
  });
  const prefix = base.startsWith("o") && i === 1 ? "K" : prefixes[i];
  if (["o", "o/s", "Hz", "W", "FLOPS"].includes(base))
    return `${text} ${prefix}${base}`;
  return `${text}${i ? " " + prefix : ""}${base ? " " + base : ""}`;
}
